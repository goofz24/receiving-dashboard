// Writes sql/02_seed.sql from the made-up data in seed-data.mjs.
// Run with:  npm run seed:generate
import { writeFileSync } from "node:fs";
import { generateSeed } from "./seed-data.mjs";

const d = generateSeed();
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const day = (n) => (n === 0 ? "current_date" : n < 0 ? `current_date - ${-n}` : `current_date + ${n}`);

function insert(table, cols, rows) {
  const values = rows.map((r) => `  (${r.join(", ")})`).join(",\n");
  return `insert into receiving.${table} (${cols.join(", ")}) overriding system value values\n${values};\n`;
}

let out = `-- =====================================================================
-- 02_seed.sql : MADE-UP sample data. Generated by scripts/generate-seed.mjs
-- Do not edit by hand; change the script and run  npm run seed:generate
--
-- Dates are written as  current_date - N  so the data always looks recent.
-- "overriding system value" lets us choose the ID numbers ourselves, so
-- the order lines can point at the right orders.
-- =====================================================================

begin;
truncate receiving.receipt_lines, receiving.receipts, receiving.po_lines,
         receiving.purchase_orders, receiving.products, receiving.suppliers;

`;
out += insert("suppliers", ["supplier_id", "name", "city", "lead_time_days"],
  d.suppliers.map((s) => [s.supplier_id, q(s.name), q(s.city), s.lead_time_days]));
out += "\n" + insert("products", ["product_id", "sku", "name", "category", "unit", "unit_cost", "supplier_id"],
  d.products.map((p) => [p.product_id, q(p.sku), q(p.name), q(p.category), q(p.unit), p.unit_cost.toFixed(2), p.supplier_id]));
out += "\n" + insert("purchase_orders", ["po_id", "po_number", "supplier_id", "ordered_on", "expected_on"],
  d.purchaseOrders.map((p) => [p.po_id, q(p.po_number), p.supplier_id, day(p.ordered_offset), day(p.expected_offset)]));
out += "\n" + insert("po_lines", ["po_line_id", "po_id", "product_id", "qty_ordered", "unit_cost"],
  d.poLines.map((l) => [l.po_line_id, l.po_id, l.product_id, l.qty_ordered, l.unit_cost.toFixed(2)]));
out += "\n" + insert("receipts", ["receipt_id", "po_id", "received_on", "received_by", "packing_slip_no"],
  d.receipts.map((r) => [r.receipt_id, r.po_id, day(r.received_offset), q(r.received_by), q(r.packing_slip_no)]));
out += "\n" + insert("receipt_lines", ["receipt_id", "po_line_id", "qty_received", "qty_damaged"],
  d.receiptLines.map((r) => [r.receipt_id, r.po_line_id, r.qty_received, r.qty_damaged]));

out += `
-- Move each ID counter past the rows we inserted, so new rows get new IDs.
${["suppliers:supplier_id", "products:product_id", "purchase_orders:po_id", "po_lines:po_line_id", "receipts:receipt_id", "receipt_lines:receipt_line_id"]
  .map((tc) => {
    const [t, c] = tc.split(":");
    return `select setval(pg_get_serial_sequence('receiving.${t}', '${c}'), (select coalesce(max(${c}), 0) + 1 from receiving.${t}), false);`;
  })
  .join("\n")}

commit;
`;

writeFileSync(new URL("../sql/02_seed.sql", import.meta.url), out);
console.log(`Wrote sql/02_seed.sql: ${d.suppliers.length} suppliers, ${d.products.length} products, ${d.purchaseOrders.length} orders, ${d.poLines.length} order lines, ${d.receipts.length} receipts, ${d.receiptLines.length} receipt lines.`);
