// Writes sql/02_seed.sql from the made-up data in seed-data.mjs, and
// sql/05_itam_seed.sql from the made-up IT asset data in itam-seed-data.mjs.
// Run with:  npm run seed:generate
import { writeFileSync } from "node:fs";
import { generateItamSeed } from "./itam-seed-data.mjs";
import { generateSeed } from "./seed-data.mjs";

const d = generateSeed();
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const day = (n) => (n === 0 ? "current_date" : n < 0 ? `current_date - ${-n}` : `current_date + ${n}`);

function insert(table, cols, rows, schema = "receiving", overriding = true) {
  const values = rows.map((r) => `  (${r.join(", ")})`).join(",\n");
  return `insert into ${schema}.${table} (${cols.join(", ")})${overriding ? " overriding system value" : ""} values\n${values};\n`;
}
const orNull = (v, f = (x) => x) => (v === null || v === undefined ? "null" : f(v));

let out = `-- =====================================================================
-- 02_seed.sql : MADE-UP sample data. Generated by scripts/generate-seed.mjs
-- Do not edit by hand; change the script and run  npm run seed:generate
--
-- Dates are written as  current_date - N  so the data always looks recent.
-- "overriding system value" lets us choose the ID numbers ourselves, so
-- the order lines can point at the right orders.
-- =====================================================================

begin;
truncate receiving.receipt_lines, receiving.receipts, receiving.po_lines,
         receiving.purchase_orders, receiving.products, receiving.suppliers;

`;
out += insert("suppliers", ["supplier_id", "name", "city", "lead_time_days"],
  d.suppliers.map((s) => [s.supplier_id, q(s.name), q(s.city), s.lead_time_days]));
out += "\n" + insert("products", ["product_id", "sku", "name", "category", "unit", "unit_cost", "supplier_id"],
  d.products.map((p) => [p.product_id, q(p.sku), q(p.name), q(p.category), q(p.unit), p.unit_cost.toFixed(2), p.supplier_id]));
out += "\n" + insert("purchase_orders", ["po_id", "po_number", "supplier_id", "ordered_on", "expected_on"],
  d.purchaseOrders.map((p) => [p.po_id, q(p.po_number), p.supplier_id, day(p.ordered_offset), day(p.expected_offset)]));
out += "\n" + insert("po_lines", ["po_line_id", "po_id", "product_id", "qty_ordered", "unit_cost"],
  d.poLines.map((l) => [l.po_line_id, l.po_id, l.product_id, l.qty_ordered, l.unit_cost.toFixed(2)]));
out += "\n" + insert("receipts", ["receipt_id", "po_id", "received_on", "received_by", "packing_slip_no"],
  d.receipts.map((r) => [r.receipt_id, r.po_id, day(r.received_offset), q(r.received_by), q(r.packing_slip_no)]));
out += "\n" + insert("receipt_lines", ["receipt_id", "po_line_id", "qty_received", "qty_damaged"],
  d.receiptLines.map((r) => [r.receipt_id, r.po_line_id, r.qty_received, r.qty_damaged]));

out += `
-- Move each ID counter past the rows we inserted, so new rows get new IDs.
${["suppliers:supplier_id", "products:product_id", "purchase_orders:po_id", "po_lines:po_line_id", "receipts:receipt_id", "receipt_lines:receipt_line_id"]
  .map((tc) => {
    const [t, c] = tc.split(":");
    return `select setval(pg_get_serial_sequence('receiving.${t}', '${c}'), (select coalesce(max(${c}), 0) + 1 from receiving.${t}), false);`;
  })
  .join("\n")}

commit;
`;

writeFileSync(new URL("../sql/02_seed.sql", import.meta.url), out);
console.log(`Wrote sql/02_seed.sql: ${d.suppliers.length} suppliers, ${d.products.length} products, ${d.purchaseOrders.length} orders, ${d.poLines.length} order lines, ${d.receipts.length} receipts, ${d.receiptLines.length} receipt lines.`);

// ------------------------------------------------------------------ IT assets
const it = generateItamSeed();
const ins = (table, cols, rows, overriding = true) => insert(table, cols, rows, "itam", overriding);
let itOut = `-- =====================================================================
-- 05_itam_seed.sql : MADE-UP sample data for the IT asset tracker.
-- Generated by scripts/generate-seed.mjs from scripts/itam-seed-data.mjs.
-- Do not edit by hand; change the script and run  npm run seed:generate
--
-- Every person, email (example.com), serial number, invoice and price is
-- invented. Dates are written as  current_date - N  so the data always
-- looks recent.
-- =====================================================================

begin;
truncate itam.license_seats, itam.licenses, itam.device_checks, itam.asset_events,
         itam.assets, itam.models, itam.employees, itam.locations;

`;
itOut += ins("locations", ["location_id", "name", "city"], it.locations.map((l) => [l.location_id, q(l.name), q(l.city)]));
itOut += "\n" + ins("employees", ["employee_id", "full_name", "email", "department", "title", "location_id", "started_on", "left_on"],
  it.employees.map((e) => [e.employee_id, q(e.full_name), q(e.email), q(e.department), q(e.title), e.location_id, day(e.started_offset), orNull(e.left_offset, day)]));
itOut += "\n" + ins("models", ["model_id", "category", "manufacturer", "model_name", "warranty_months", "useful_life_months"],
  it.models.map((m) => [m.model_id, q(m.category), q(m.manufacturer), q(m.model_name), m.warranty_months, m.useful_life_months]));
itOut += "\n" + ins("assets", ["asset_id", "asset_tag", "serial_number", "model_id", "vendor", "invoice_number", "purchased_on", "purchase_cost", "warranty_ends_on", "location_id"],
  it.assets.map((a) => [a.asset_id, q(a.asset_tag), q(a.serial_number), a.model_id, q(a.vendor), q(a.invoice_number), day(a.purchased_offset), a.purchase_cost.toFixed(2), day(a.warranty_offset), a.location_id]));
itOut += "\n" + ins("asset_events", ["event_id", "asset_id", "event_on", "event_type", "employee_id", "done_by", "note"],
  it.events.map((x) => [x.event_id, x.asset_id, day(x.event_offset), q(x.event_type), orNull(x.employee_id), q(x.done_by), orNull(x.note, q)]));
itOut += "\n" + ins("device_checks", ["check_id", "asset_id", "checked_on", "os_version", "bitlocker_on", "disk_free_pct", "pending_updates"],
  it.checks.map((c) => [c.check_id, c.asset_id, day(c.checked_offset), q(c.os_version), String(c.bitlocker_on), c.disk_free_pct.toFixed(1), c.pending_updates]));
itOut += "\n" + ins("licenses", ["license_id", "product", "vendor", "seats_owned", "cost_per_seat_year", "renews_on"],
  it.licenses.map((l) => [l.license_id, q(l.product), q(l.vendor), l.seats_owned, l.cost_per_seat_year.toFixed(2), day(l.renews_offset)]));
itOut += "\n" + ins("license_seats", ["license_id", "employee_id", "assigned_on"],
  it.seats.map((x) => [x.license_id, x.employee_id, day(x.assigned_offset)]), false);

itOut += `
-- Move each ID counter past the rows we inserted, so new rows get new IDs.
${["locations:location_id", "employees:employee_id", "models:model_id", "assets:asset_id", "asset_events:event_id", "device_checks:check_id", "licenses:license_id"]
  .map((tc) => {
    const [t, c] = tc.split(":");
    return `select setval(pg_get_serial_sequence('itam.${t}', '${c}'), (select coalesce(max(${c}), 0) + 1 from itam.${t}), false);`;
  })
  .join("\n")}

commit;
`;

writeFileSync(new URL("../sql/05_itam_seed.sql", import.meta.url), itOut);
console.log(`Wrote sql/05_itam_seed.sql: ${it.employees.length} employees, ${it.assets.length} assets, ${it.events.length} events, ${it.checks.length} health checks, ${it.licenses.length} licenses, ${it.seats.length} seats.`);
